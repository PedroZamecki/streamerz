/// Icon `name`, `size` px square, stroked in `c`.
pub fn icon(name: &str, c: Color, size: i32) -> Option<SvgImage> {
    make(name, c, size, 0)
}

/// `icon` with a gap after it, to sit before a label.
pub fn before_label(name: &str, c: Color, size: i32) -> Option<SvgImage> {
    make(name, c, size, size / 2)
}

fn make(name: &str, c: Color, size: i32, gap: i32) -> Option<SvgImage> {
    /// By name, colour, size and gap.
    type Key = (String, u32, i32, i32);
    thread_local!(static CACHE: RefCell<HashMap<Key, Option<SvgImage>>> = RefCell::default());
    let (r, g, b) = c.to_rgb();
    CACHE.with_borrow_mut(|m| {
        m.entry((name.to_string(), c.bits(), size, gap))
            .or_insert_with(|| {
                let body = ICONS.iter().find(|i| i.0 == name)?.1;
                let vw = 24 + 24 * gap / size;
                let svg = format!(
                    r##"<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {vw} 24" fill="none" stroke="#{r:02x}{g:02x}{b:02x}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">{body}</svg>"##
                );
                let mut i = SvgImage::from_data(&svg).ok()?;
                i.scale(size + gap, size, false, true);
                Some(i)
            })
            .clone()
    })
}

